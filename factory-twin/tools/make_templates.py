def sheet(name, cols, note, widths=None, rows=30):
    ws = wb.create_sheet(name)
    ws.append([note]); ws["A1"].font = NOTE
    ws.append(cols)
    for c in ws[2]:
        c.fill = H; c.font = HF; c.alignment = Alignment(wrap_text=True, vertical="center")
